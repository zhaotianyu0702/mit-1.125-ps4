#!/usr/bin/env python3
"""Archive a plainly labeled official-fixture replay without touching the live index."""
import datetime as dt
import json
import os
from pathlib import Path
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / 'docs/validation/fixture-replay'

def main():
    DEST.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='ps4-fixture-replay-') as tmp:
        copy = Path(tmp) / 'ps4'
        for folder in ('lib', 'data', 'processing', 'collectors', 'examples'):
            shutil.copytree(ROOT / folder, copy / folder,
                            ignore=shutil.ignore_patterns('evidence', 'assets', 'media', '__pycache__'))
        run = copy / 'runs/fixture-replay'
        run.mkdir(parents=True)
        meta = json.loads((ROOT / 'examples/run.json').read_text())
        meta.update(run_id='fixture-replay', mode='replay', fixture_notice='Fictional official interface examples, never live evidence.')
        (run / 'run.json').write_text(json.dumps(meta, indent=2) + '\n')
        (run / 'config').mkdir()
        (run / 'config/sources.json').write_text(json.dumps([{'source_id': 'deliberate-local-failure', 'publisher_id': 'fictional', 'kind': 'feed', 'url': 'http://127.0.0.1:1/intentional-unavailable-fixture-feed'}]))
        env = dict(os.environ, PS4_RUN_DIR=str(run), PYTHONDONTWRITEBYTECODE='1')
        def call(argv, output, source=None, expected=0):
            p = subprocess.run(argv, input=(copy/source).read_text() if source else '',
                               text=True, capture_output=True, cwd=copy, env=env)
            (DEST/output).write_text(p.stdout)
            (DEST/(output+'.stderr')).write_text(p.stderr)
            if p.returncode != expected:
                raise RuntimeError(f'{argv} returned {p.returncode}, expected {expected}')
        call(['bash','data/store.sh','init'], 'store-init.txt')
        call(['bash','data/store.sh','upsert','runs/fixture-replay'], 'initial_changes.jsonl', 'examples/items.jsonl')
        call(['bash','data/store.sh','upsert','runs/fixture-replay'], 'replay_changes.jsonl', 'examples/replay_items.jsonl')
        call(['bash','data/store.sh','list'], 'latest.jsonl')
        first = json.loads((copy/'examples/items.jsonl').read_text().splitlines()[-1])
        call(['bash','data/store.sh','get',first['item_id'],first['version_id']], 'retained_original_version.jsonl')
        call(['bash','processing/filter_items.sh','runs/fixture-replay'], 'eligible.jsonl', 'examples/filter_input.jsonl')
        call(['bash','collectors/fetch_feeds.sh','runs/fixture-replay'], 'simulated_collection_failure.jsonl', expected=1)
        for name in ('run.json','exclusions.jsonl'):
            shutil.copyfile(run/name, DEST/name)
        if (DEST/'logs').exists():
            shutil.rmtree(DEST/'logs')
        shutil.copytree(run/'logs', DEST/'logs')
    (DEST/'README.md').write_text('# Fictional fixture replay — not a live run\n\n'
        'Generated by `python3 tests/save_fixture_replay.py` in a disposable project copy. '
        'No fixture records entered the live evidence index. `run.json` uses the official examples’ fixed date, labeled replay. '
        'This does not count toward the two different-day live runs.\n\n'
        'The first ingestion has three new items. The second has four unchanged observations and one changed version. '
        'The store still has three logical items and the original podcast version remains retrievable. '
        'The filter separately records unknown, invalid, future and out-of-window dates. '
        'The collector deliberately attempts an unavailable local port and records a failure, not a successful empty feed. '
        'This failure is simulated; the first live run separately recorded genuine YouTube caption HTTP 429 failures.\n')
    print(json.dumps({'status':'passed','mode':'replay','artifact':str(DEST.relative_to(ROOT)), 'executed_at':dt.datetime.now(dt.timezone.utc).isoformat()}))

if __name__ == '__main__':
    main()
